uint32_t XcpHw_GetTimerCounter(void)
{
    if (s_ticksPerMs == 0u || s_ticksPerUs == 0u)
    {
        return 0u;
    }

#if XCP_DAQ_TIMESTAMP_UNIT == XCP_DAQ_TIMESTAMP_UNIT_1US
    return (uint32)(IfxStm_get(&XCP_STM_MODULE) / (uint64)s_ticksPerUs); 
#elif XCP_DAQ_TIMESTAMP_UNIT == XCP_DAQ_TIMESTAMP_UNIT_1MS
    return (uint32)(IfxStm_get(&XCP_STM_MODULE) / (uint64)s_ticksPerMs);
#endif

    return 0;
}

uint32_t XcpHw_GetTimerCounterMS(void)
{
    if (s_ticksPerMs == 0u)
    {
        return 0u;
    }

    return (uint32)(IfxStm_get(&XCP_STM_MODULE) / (uint64)s_ticksPerMs);
}

void XcpHw_AcquireLock(uint8_t lockIdx)
{
    if (lockIdx >= XCP_HW_LOCK_COUNT)
    {
        return;
    } 

    while (!IfxCpu_acquireMutex(&g_xcp_mutex[lockIdx]))
    {
        // Wait until we aquire the mutex        
    }
}

void XcpHw_ReleaseLock(uint8_t lockIdx)
{
    if (lockIdx >= XCP_HW_LOCK_COUNT)
    {
        return;
    }

    IfxCpu_releaseMutex(&g_xcp_mutex[lockIdx]);
}